"""Short-term lesson plan (KSP) generation.

Uses OpenRouter when OPENROUTER_API_KEY is set, otherwise a deterministic mock,
so development, tests and CI never call a paid external API.
"""

import json
import os
import urllib.error
import urllib.request

OPENROUTER_URL = "https://openrouter.ai/api/v1/chat/completions"
DEFAULT_MODEL = "openai/gpt-4o-mini"
TIMEOUT_SECONDS = 60

SYSTEM_PROMPT = (
    "You are an assistant for school teachers in Kazakhstan. Write a short-term "
    "lesson plan (KSP) in Markdown with these sections: Lesson information, "
    "Learning objectives, Success criteria, Lesson stages (Beginning, Middle, End) "
    "with teacher and student activities and timing, Assessment, Differentiation, "
    "Resources, Reflection."
)


class AIServiceError(Exception):
    pass


def generate_plan(
    subject: str, grade: int, topic: str, objectives: str | None
) -> tuple[str, str]:
    """Return (markdown content, source) where source is "openrouter" or "mock"."""
    api_key = os.getenv("OPENROUTER_API_KEY")
    if not api_key:
        return mock_plan(subject, grade, topic, objectives), "mock"
    prompt = build_prompt(subject, grade, topic, objectives)
    return call_openrouter(api_key, prompt), "openrouter"


def build_prompt(subject: str, grade: int, topic: str, objectives: str | None) -> str:
    prompt = f"Subject: {subject}\nGrade: {grade}\nTopic: {topic}\nDuration: 45 minutes"
    if objectives:
        prompt += f"\nLearning objectives from the curriculum: {objectives}"
    return prompt


def call_openrouter(api_key: str, prompt: str) -> str:
    body = {
        "model": os.getenv("OPENROUTER_MODEL", DEFAULT_MODEL),
        "messages": [
            {"role": "system", "content": SYSTEM_PROMPT},
            {"role": "user", "content": prompt},
        ],
    }
    request = urllib.request.Request(
        OPENROUTER_URL,
        data=json.dumps(body).encode(),
        headers={
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(request, timeout=TIMEOUT_SECONDS) as response:
            data = json.load(response)
        return data["choices"][0]["message"]["content"]
    except (urllib.error.URLError, TimeoutError, KeyError, IndexError) as error:
        raise AIServiceError(f"OpenRouter request failed: {error}") from error


def mock_plan(subject: str, grade: int, topic: str, objectives: str | None) -> str:
    goals = objectives or f"Understand and apply the key ideas of the topic {topic}."
    return f"""# Short-term plan: {topic}

## Lesson information
- Subject: {subject}
- Grade: {grade}
- Duration: 45 minutes

## Learning objectives
- {goals}

## Success criteria
- Explains the main concepts of "{topic}" in own words.
- Solves at least two typical tasks on the topic.

## Lesson stages
| Stage | Time | Teacher | Students |
|---|---|---|---|
| Beginning | 5 min | Greets the class, sets objectives, asks warm-up questions | Answer questions, recall previous lesson |
| Middle | 30 min | Explains "{topic}", organizes pair work and task solving | Take notes, work in pairs, present solutions |
| End | 10 min | Summarizes, gives homework, collects feedback | Self-assessment with success criteria, reflection |

## Assessment
- Formative assessment with descriptors and teacher feedback.

## Differentiation
- Support cards for students who need help, extra tasks for advanced students.

## Resources
- Textbook, presentation, worksheets.

## Reflection
- What went well? What should be changed next lesson?

_Generated by the mock AI service. Set OPENROUTER_API_KEY to use OpenRouter._
"""
